import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import type { StudentData } from './engine';

export const generateTranscriptPDF = (student: StudentData) => {
  const doc = new jsPDF();
  const brandColor = [79, 70, 229]; // Indigo-600
  const nexusLogo = '/nexuslogo.png';

  // 1. Header & Logo
  doc.addImage(nexusLogo, 'PNG', 170, 10, 25, 25);
  doc.setFontSize(8);
  doc.setTextColor(60, 60, 60);
  doc.setFont('helvetica', 'bold');
  doc.text('NEXUS AI DIGITAL', 182.5, 38, { align: 'center' });
  
  doc.setFontSize(22);
  doc.setTextColor(40, 40, 40);
  doc.setFont('helvetica', 'bold');
  doc.text('University of Agriculture, Faisalabad', 15, 22);
  
  doc.setFontSize(10);
  doc.setTextColor(100, 100, 100);
  doc.setFont('helvetica', 'normal');
  doc.text('Unofficial Academic Transcript - Internal Record', 15, 28);

  // 2. Student Details Box
  doc.setDrawColor(230, 230, 230);
  doc.setFillColor(252, 253, 255);
  doc.roundedRect(15, 40, 180, 25, 3, 3, 'FD');

  doc.setFontSize(9);
  doc.setTextColor(120, 120, 120);
  doc.text('STUDENT NAME', 20, 48);
  doc.text('REGISTRATION NUMBER', 20, 58);
  doc.text('CUMULATIVE GPA', 130, 48);
  doc.text('DEGREE PROGRAM', 130, 58);

  doc.setFontSize(11);
  doc.setTextColor(20, 20, 20);
  doc.setFont('helvetica', 'bold');
  doc.text(student.name.toUpperCase(), 20, 53);
  doc.text(student.ag_number.toUpperCase(), 20, 63);
  doc.text(student.cgpa.toFixed(2), 130, 53);
  doc.text('BS COMPUTER SCIENCE', 130, 63);

  let currentY = 75;
  let regularSemCount = 1;
  const sortedSems = [...student.semesters].sort((a, b) => a.semester_number - b.semester_number);

  // 3. Semester Tables
  sortedSems.forEach((sem) => {
    const isSummer = sem.session_name.toLowerCase().includes('summer');
    const visualLabel = isSummer ? 'SUMMER SESSION' : `SEM ${regularSemCount}`;
    if (!isSummer) regularSemCount++;

    // Better page break check: header + approx table height
    const estimatedHeight = 25 + (sem.subjects.length * 8);
    if (currentY + estimatedHeight > 275) {
      doc.addPage();
      currentY = 20;
    }

    doc.setFontSize(11);
    doc.setTextColor(...brandColor);
    doc.setFont('helvetica', 'bold');
    doc.text(`${sem.session_name.toUpperCase()} (${visualLabel})`, 15, currentY);
    
    doc.setFontSize(9);
    doc.setTextColor(100, 100, 100);
    doc.text(`Semester GPA: ${sem.sgpa.toFixed(2)}`, 160, currentY);

    autoTable(doc, {
      startY: currentY + 5,
      head: [['Course Code', 'Course Title', 'Credit Hrs', 'Total', 'Grade']],
      body: sem.subjects.map(sub => [
        sub.course_code,
        sub.name,
        `${sub.credit_hours}(${sub.credit_hours}-${sub.credit_hours > 2 ? '1' : '0'})`,
        sub.obtained_marks,
        sub.grade
      ]),
      styles: { fontSize: 8, cellPadding: 3 },
      headStyles: { 
        fillColor: brandColor, 
        textColor: 255, 
        fontStyle: 'bold',
        halign: 'left'
      },
      alternateRowStyles: { fillColor: [250, 251, 255] },
      margin: { left: 15, right: 15 },
      theme: 'striped',
      pageBreak: 'auto'
    });

    currentY = (doc as any).lastAutoTable.finalY + 15;
  });

  // 4. Footer
  const pageCount = (doc as any).internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setDrawColor(240, 240, 240);
    doc.line(15, 280, 195, 280);
    
    doc.setFontSize(8);
    doc.setTextColor(150, 150, 150);
    doc.text('Generated by Nexus AI Digital Academic System', 15, 287);
    doc.text('Developed by: Zohaib Muaz', 155, 287);
    doc.text(`Page ${i} of ${pageCount}`, 100, 287, { align: 'center' });
  }

  doc.save(`${student.ag_number}_transcript.pdf`);
};

export const generateClassReportPDF = (students: any[], sortMode: 'ranked' | 'original' = 'ranked') => {
  const doc = new jsPDF();
  const brandColor = [79, 70, 229];
  const nexusLogo = '/nexuslogo.png';

  // Header
  doc.addImage(nexusLogo, 'PNG', 170, 10, 25, 25);
  doc.setFontSize(8);
  doc.setTextColor(60, 60, 60);
  doc.setFont('helvetica', 'bold');
  doc.text('NEXUS AI DIGITAL', 182.5, 38, { align: 'center' });

  doc.setFontSize(22);
  doc.setFont('helvetica', 'bold');
  doc.text('Class Performance Report', 15, 22);
  
  doc.setFontSize(10);
  doc.setTextColor(100, 100, 100);
  doc.setFont('helvetica', 'normal');
  doc.text(`Total Students Evaluated: ${students.length}`, 15, 28);

  autoTable(doc, {
    startY: 40,
    head: [[sortMode === 'ranked' ? 'Rank' : '#', 'Student Name', 'Registration ID', 'Courses', 'Cumulative GPA']],
    body: students.map((s, index) => [
      sortMode === 'ranked' ? `#${s.globalRank}` : `${index + 1}`,
      s.name.toUpperCase(),
      s.ag_number.toUpperCase(),
      s.semesters.reduce((acc: number, sem: any) => acc + sem.subjects.length, 0),
      s.cgpa.toFixed(2)
    ]),
    headStyles: { fillColor: brandColor, textColor: 255, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: [248, 250, 255] },
    styles: { fontSize: 9, cellPadding: 5 },
    columnStyles: {
      0: { fontStyle: 'bold', cellWidth: 20 },
      4: { fontStyle: 'bold', halign: 'right' }
    },
    theme: 'striped'
  });

  // Footer
  const pageCount = (doc as any).internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(150, 150, 150);
    doc.text('Confidential Academic Record | Generated via Nexus AI Digital', 15, 287);
    doc.text('Developed by: Zohaib Muaz', 155, 287);
  }

  doc.save(`Class_Performance_Report.pdf`);
};
